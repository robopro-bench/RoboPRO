"""Replay recorded robot trajectories to collect additional information.

Given a previously collected dataset (produced by ``collect_data.py``), this
script reconstructs each episode's scene, restores the *explicit* recorded
initial state (object poses, articulation & robot qpos), then replays the saved
planned joint trajectory via ``play_once(need_plan=False)`` while recording a
(possibly richer) set of observation modalities into a fresh HDF5 dataset.

Why the seed still appears: ``play_once`` dereferences seed-generated, per-task
handles (e.g. ``self.boxdrink`` / ``self.des_pose``) and ``_traj_data`` stores
only the arm joint paths (gripper timing + attach events are regenerated by
re-running ``play_once``). So we run the seeded setup ONLY to wire those handles,
then ``restore_init_state`` overrides every physical state from the record — the
recorded state is authoritative.

Usage:
    python script/replay_trajectory.py <task_name> <collection_config> \
        [--replay-config replay_rich] [--out-subdir replay]

``<collection_config>`` is the task_config used at collection time (its
scene/camera/embodiment/domain-randomization settings must match so the seeded
setup reproduces the same scene + handles). ``--replay-config`` is a small YAML
that overlays extra ``data_type`` modalities and an optional output ``save_path``.
"""

