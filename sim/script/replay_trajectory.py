def _load_yaml(path):
    with open(path, "r", encoding="utf-8") as f:
        return yaml.load(f.read(), Loader=yaml.FullLoader)


def build_collection_args(task_name, task_config):
    """Build the run args from a collection task_config, mirroring
    ``collect_data.main`` up to (but not including) ``run``."""
    from script.task_loader import bench_config_path
    task_config_path = bench_config_path(task_config)

    args = _load_yaml(task_config_path)
    args["task_name"] = task_name
    args["task_config"] = task_config

    embodiment_type = args.get("embodiment")
    embodiment_config_path = os.path.join(CONFIGS_PATH, "_embodiment_config.yml")
    _embodiment_types = _load_yaml(embodiment_config_path)

    def get_embodiment_file(embodiment_type_name):
        robot_file = _embodiment_types[embodiment_type_name]["file_path"]
        if robot_file is None:
            raise SystemExit("missing embodiment files")
        return robot_file

    if len(embodiment_type) == 1:
        args["left_robot_file"] = get_embodiment_file(embodiment_type[0])
        args["right_robot_file"] = get_embodiment_file(embodiment_type[0])
        args["dual_arm_embodied"] = True
        embodiment_name = str(embodiment_type[0])
    elif len(embodiment_type) == 3:
        args["left_robot_file"] = get_embodiment_file(embodiment_type[0])
        args["right_robot_file"] = get_embodiment_file(embodiment_type[1])
        args["embodiment_dis"] = embodiment_type[2]
        args["dual_arm_embodied"] = False
        embodiment_name = str(embodiment_type[0]) + "+" + str(embodiment_type[1])
    else:
        raise SystemExit("embodiment config should have 1 or 3 entries")

    args["left_embodiment_config"] = get_embodiment_config(args["left_robot_file"])
    args["right_embodiment_config"] = get_embodiment_config(args["right_robot_file"])
    args["embodiment_name"] = embodiment_name
    return args


def _read_seed_list(source_dir):
    seed_path = os.path.join(source_dir, "seed.txt")
    if not os.path.exists(seed_path):
        raise SystemExit(f"No seed.txt under source dir: {source_dir}")
    with open(seed_path, "r") as f:
        return [int(s) for s in f.read().split()]


def run_replay(TASK_ENV, args, source_dir, replay_dir):
    seed_list = _read_seed_list(source_dir)
    episode_num = min(args.get("episode_num", len(seed_list)), len(seed_list))

    # Replay never plans; it replays the recorded joint paths and records data.
    args["need_plan"] = False
    args["save_data"] = True
    args["render_freq"] = 0
    # Writes (data/, video/, .cache/) go to the replay dir; reads (_traj_data,
    # episode*_init.json) come from the source dir via traj_src_dir.
    args["save_path"] = replay_dir
    os.makedirs(os.path.join(replay_dir, "data"), exist_ok=True)

    clear_cache_freq = args.get("clear_cache_freq", 1)
    suc, fail = 0, 0

    for episode_idx in range(episode_num):
        traj_pkl = os.path.join(source_dir, "_traj_data", f"episode{episode_idx}.pkl")
        if not os.path.exists(traj_pkl):
            print(f"\033[93m[skip] no trajectory for episode {episode_idx}: {traj_pkl}\033[0m")
            continue

        hdf5_path = os.path.join(replay_dir, "data", f"episode{episode_idx}.hdf5")
        if os.path.exists(hdf5_path):
            print(f"[skip] already replayed episode {episode_idx}")
            continue

        seed = seed_list[episode_idx]
        print(f"\033[34mReplay {args['task_name']} episode {episode_idx} (seed={seed})\033[0m")

        try:
            # 1) Seeded setup wires task handles + gripper/attach structure.
            TASK_ENV.setup_demo(now_ep_num=episode_idx, seed=seed, **args)
            if hasattr(TASK_ENV, "_maybe_apply_language_perturbation"):
                TASK_ENV._maybe_apply_language_perturbation()

            # Reads come from the source collection; writes go to replay_dir.
            TASK_ENV.traj_src_dir = source_dir
            TASK_ENV.save_dir = replay_dir

            # 2) Explicit recorded state is authoritative.
            try:
                state = TASK_ENV.load_init_state(episode_idx)
                TASK_ENV.restore_init_state(state)
            except FileNotFoundError:
                print(f"\033[93m[warn] no init-state for episode {episode_idx}; "
                      f"relying on seed regeneration\033[0m")

            # 3) Load + install the recorded joint trajectory.
            traj_data = TASK_ENV.load_tran_data(episode_idx)
            args["left_joint_path"] = traj_data["left_joint_path"]
            args["right_joint_path"] = traj_data["right_joint_path"]
            TASK_ENV.set_path_lst(args)

            # 4) Replay; observations are recorded by _take_picture.
            TASK_ENV.play_once()

            TASK_ENV.close_env(clear_cache=((episode_idx + 1) % clear_cache_freq == 0))
            TASK_ENV.merge_pkl_to_hdf5_video()
            TASK_ENV.remove_data_cache()

            if not TASK_ENV.check_success():
                print(f"\033[91m[fail] replay of episode {episode_idx} did not succeed; removing\033[0m")
                for p in (hdf5_path,
                          os.path.join(replay_dir, "video", f"episode{episode_idx}.mp4")):
                    if os.path.exists(p):
                        os.remove(p)
                fail += 1
                continue
            suc += 1
        except UnStableError as e:
            print(f"\033[91m[fail] episode {episode_idx}: UnStableError {e}\033[0m")
            fail += 1
            try:
                TASK_ENV.close_env()
            except Exception:
                pass
        except Exception as e:
            print(f"\033[91m[fail] episode {episode_idx}: {e}\033[0m")
            print(traceback.format_exc())
            fail += 1
            try:
                TASK_ENV.close_env()
            except Exception:
                pass

    print(f"\nReplay complete: \033[92m{suc}\033[0m ok / \033[91m{fail}\033[0m failed "
          f"-> {os.path.join(replay_dir, 'data')}")


def main(task_name, task_config, replay_config=None, out_subdir="replay"):
    task = class_decorator(task_name)
    args = build_collection_args(task_name, task_config)

    collection_base = args["save_path"]
    replay_base = collection_base

    # Overlay replay-only overrides (extra modalities + output location).
    if replay_config:
        from script.task_loader import bench_config_path
        rcfg_path = str(bench_config_path(replay_config))
        rcfg = _load_yaml(rcfg_path)
        for k, v in (rcfg.get("data_type") or {}).items():
            args.setdefault("data_type", {})[k] = v
        if rcfg.get("save_path"):
            replay_base = rcfg["save_path"]
        if rcfg.get("out_subdir"):
            out_subdir = rcfg["out_subdir"]
        if rcfg.get("save_freq") is not None:
            args["save_freq"] = rcfg["save_freq"]
        if rcfg.get("camera"):
            args.setdefault("camera", {}).update(rcfg["camera"])

    source_dir = os.path.join(collection_base, task_name, task_config)
    replay_dir = os.path.join(replay_base, task_name, f"{task_config}_{out_subdir}")

    print("============= Replay Config =============")
    print(f"task         : {task_name}")
    print(f"collection   : {task_config}")
    print(f"source dir   : {source_dir}")
    print(f"replay dir   : {replay_dir}")
    print(f"data_type    : {args.get('data_type')}")
    print("=========================================")

    run_replay(task, args, source_dir, replay_dir)


